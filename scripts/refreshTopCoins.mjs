#!/usr/bin/env node
// Captures the same CoinGecko market-cap top 100 that Home displays. News
// tagging needs this identifier list in the scheduled Node job, where the
// browser's live CoinContext is not available.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const OUTPUT = fileURLToPath(new URL('../src/constants/topCoins.js', import.meta.url));
const API_KEY = process.env.COINGECKO_API_KEY || process.env.VITE_COINGECKO_API_KEY || '';
const API_BASE = process.env.COINGECKO_API_BASE_URL || 'https://api.coingecko.com/api/v3';

const response = await fetch(
  `${API_BASE}/coins/markets?vs_currency=usd&order=market_cap_desc&per_page=100&page=1&sparkline=false`,
  {
    headers: {
      accept: 'application/json',
      'user-agent': 'crypto-price-tracker/1.0 (top-100 identifier snapshot)',
      ...(API_KEY ? { 'x-cg-demo-api-key': API_KEY } : {}),
    },
    signal: AbortSignal.timeout(20000),
  },
);

if (!response.ok) {
  throw new Error(`CoinGecko markets failed: ${response.status} ${response.statusText}`);
}

const markets = await response.json();
if (!Array.isArray(markets) || markets.length < 90) {
  throw new Error('CoinGecko did not return the expected top-100 markets');
}

const coins = markets.slice(0, 100).map(({ id, symbol, name }) => ({ id, symbol, name }));
const source = `// Generated by scripts/refreshTopCoins.mjs from CoinGecko's market-cap top 100.\n// Home fetches live prices; this static identifier snapshot is only for news tagging.\nexport const TOP_COINS = ${JSON.stringify(coins, null, 2)};\n\nexport const COIN_BY_ID = Object.fromEntries(TOP_COINS.map((coin) => [coin.id, coin]));\n`;

let previous = '';
try {
  previous = await readFile(OUTPUT, 'utf8');
} catch {
  // First snapshot.
}

if (previous !== source) {
  await writeFile(OUTPUT, source);
  console.log(`[coins] Wrote ${coins.length} identifiers to src/constants/topCoins.js`);
} else {
  console.log('[coins] Top-100 identifiers unchanged');
}
